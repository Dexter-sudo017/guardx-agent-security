def load_benchmark_cases() -> list[BenchmarkCase]:
    cases: list[BenchmarkCase] = []
    with SAFE_INDEX_PATH.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            case_id = row["case_id"].strip()
            content = SAFE_CASE_CONTENT.get(case_id)
            if not content:
                continue

            cases.append(
                BenchmarkCase(
                    case_id=case_id,
                    layer=row["layer"].strip(),
                    attack_type=row["attack_type"].strip(),
                    risk_area=row["risk_area"].strip(),
                    source_reference=row["source_reference"].strip(),
                    raw_prompt_policy=row["raw_prompt_policy"].strip(),
                    expected_defense_action=row["expected_defense_action"].strip(),
                    metric=row["metric"].strip(),
                    mode=content["mode"],
                    expected_guard_result=content["expected_guard_result"],
                    risky=content["risky"],
                    message=content.get("message", ""),
                    history=content.get("history", []),
                    context_chunks=content.get("context_chunks", []),
                    tool_name=content.get("tool_name"),
                    tool_args=content.get("tool_args", {}),
                    tool_sequence=content.get("tool_sequence", []),
                    risk_hint=content.get("risk_hint"),
                    ocr_text=content.get("ocr_text", ""),
                    vlm_answer=content.get("vlm_answer"),
                    notes=content.get("notes", ""),
                    split="safe",
                )
            )
    return cases
