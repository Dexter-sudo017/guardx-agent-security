def list_eval_suites() -> list[dict]:
    return [
        {
            "id": suite.id,
            "label": suite.label,
            "description": suite.description,
            "intended_targets": suite.intended_targets,
            "case_ids": suite.case_ids,
            "budget_friendly": suite.budget_friendly,
        }
        for suite in EVAL_SUITES
    ]


def resolve_suite_case_ids(suite_id: str | None) -> list[str] | None:
    if not suite_id:
        return None
    for suite in EVAL_SUITES:
        if suite.id == suite_id:
            return suite.case_ids
    return None

